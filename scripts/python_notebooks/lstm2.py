# Create sequences for LSTM
def create_sequences(data, n_steps_in=12, n_steps_out=1):
    X, y = [], []
    for i in range(len(data) - n_steps_in - n_steps_out + 1):
        X.append(data[i:i+n_steps_in])
        y.append(data[i+n_steps_in:i+n_steps_in+n_steps_out])
    return np.array(X), np.array(y)

# Function to build and train LSTM model for a grid
def train_lstm_model(grid_id, rainfall_data):
    # Filter data for this grid
    grid_cell_data = rainfall_data[rainfall_data['Grid_ID'] == grid_id]

    # Create a time series dataframe with Date as index and Rainfall as values
    ts_data = grid_cell_data[['Date', 'Rainfall']].copy()
    ts_data.set_index('Date', inplace=True)

    # Monthly aggregation - CHANGED TO MEAN (AVERAGE) INSTEAD OF SUM
    monthly_data = ts_data.resample('M').mean()

    # Add month as a feature (to capture seasonality)
    monthly_data['month'] = monthly_data.index.month

    # Use all data for training (we'll forecast future months)
    train_data = monthly_data

    # Normalize the data
    scaler_rainfall = MinMaxScaler(feature_range=(0, 1))
    scaler_month = MinMaxScaler(feature_range=(0, 1))

    train_rainfall_scaled = scaler_rainfall.fit_transform(train_data[['Rainfall']])
    train_month_scaled = scaler_month.fit_transform(train_data[['month']])

    # Combine features
    train_scaled = np.hstack((train_rainfall_scaled, train_month_scaled))

    # Create sequences for LSTM - use 13 months to capture seasonality (as per research)
    n_steps_in = 13  # Research shows this is optimal for rainfall
    n_steps_out = 1  # Predict one month ahead

    # Ensure we have enough data
    if len(train_scaled) <= n_steps_in:
        print(f"Not enough training data for Grid {grid_id}")
        return None

    X_train, y_train = create_sequences(train_scaled, n_steps_in, n_steps_out)

    # Reshape y_train to match model output
    y_train = y_train[:, 0, 0].reshape(-1, 1)

    # Define input shape
    input_shape = (n_steps_in, train_scaled.shape[1])

    # Define LSTM model with parameters from research
    model = Sequential()
    model.add(Bidirectional(LSTM(64, activation='relu', return_sequences=True), input_shape=input_shape))
    model.add(Dropout(0.2))  # Research shows 0.2 is optimal for rainfall
    model.add(LSTM(32, activation='relu'))
    model.add(Dropout(0.2))
    model.add(Dense(1))

    # Use Adam optimizer with learning rate from research
    optimizer = tf.keras.optimizers.Adam(learning_rate=0.005)
    model.compile(optimizer=optimizer, loss='mse')

    # Use early stopping to prevent overfitting
    early_stopping = EarlyStopping(
        monitor='val_loss',
        patience=15,
        restore_best_weights=True
    )

    # Fit model with validation split
    model.fit(
        X_train, y_train,
        epochs=50,  # Research shows 50 epochs is sufficient
        batch_size=32,  # Research shows batch size of 32 is optimal
        validation_split=0.2,
        callbacks=[early_stopping],
        verbose=0
    )

    return {
        'model': model,
        'scaler_rainfall': scaler_rainfall,
        'scaler_month': scaler_month,
        'last_sequence': train_scaled[-n_steps_in:],
        'last_date': monthly_data.index[-1]
    }

# Function to forecast future rainfall (UPDATED FOR 2026)
def forecast_lstm(model_info, forecast_steps=24):  # Changed to 24 months (2025-2026)
    model = model_info['model']
    scaler_rainfall = model_info['scaler_rainfall']
    scaler_month = model_info['scaler_month']
    input_seq = model_info['last_sequence']
    last_date = model_info['last_date']

    # Generate forecast dates
    forecast_index = pd.date_range(
        start=last_date + pd.DateOffset(months=1),
        periods=forecast_steps,
        freq='M'
    )

    # Prepare month features for forecast period
    forecast_months = np.array([date.month for date in forecast_index]).reshape(-1, 1)
    forecast_months_scaled = scaler_month.transform(forecast_months)

    # Make predictions for forecast period
    forecasts = []

    # Use the last sequence from training data as initial input
    curr_seq = input_seq.copy()

    for i in range(forecast_steps):
        # Reshape for prediction
        x_input = curr_seq.reshape(1, curr_seq.shape[0], curr_seq.shape[1])

        # Predict next value
        yhat = model.predict(x_input, verbose=0)

        # Store prediction
        forecasts.append(yhat[0, 0])

        # Update sequence for next prediction
        # Remove first element and add prediction + next month
        curr_seq = np.vstack((curr_seq[1:],
                              np.array([[yhat[0, 0], forecast_months_scaled[i, 0]]])))

    # Convert predictions back to original scale
    forecasts = np.array(forecasts).reshape(-1, 1)
    forecasts = scaler_rainfall.inverse_transform(forecasts)

    return {
        'forecast_index': forecast_index,
        'forecasts': forecasts.flatten()
    }

