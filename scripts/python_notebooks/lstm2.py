# Create sequences for LSTM
def create_sequences(data, n_steps_in=12, n_steps_out=1):
    X, y = [], []
    for i in range(len(data) - n_steps_in - n_steps_out + 1):
        X.append(data[i:i+n_steps_in])
        y.append(data[i+n_steps_in:i+n_steps_in+n_steps_out])
    return np.array(X), np.array(y)

# --- MODIFIED: Train LSTM model with ENSO feature ---
def train_lstm_model(grid_id, combined_data):
    grid_cell_data = combined_data[combined_data['Grid_ID'] == grid_id]
    ts_data = grid_cell_data[['Date', 'Rainfall', 'ONI']].copy().set_index('Date')

    monthly_data = ts_data.resample('M').mean()
    monthly_data['month'] = monthly_data.index.month
    train_data = monthly_data[['Rainfall', 'month', 'ONI']].dropna()

    scaler_rainfall = MinMaxScaler(feature_range=(0, 1))
    scaler_month = MinMaxScaler(feature_range=(0, 1))
    scaler_oni = MinMaxScaler(feature_range=(0, 1))

    train_rainfall_scaled = scaler_rainfall.fit_transform(train_data[['Rainfall']])
    train_month_scaled = scaler_month.fit_transform(train_data[['month']])
    train_oni_scaled = scaler_oni.fit_transform(train_data[['ONI']])

    train_scaled = np.hstack((train_rainfall_scaled, train_month_scaled, train_oni_scaled))

    n_steps_in = 13
    if len(train_scaled) <= n_steps_in:
        print(f"Not enough training data for Grid {grid_id}")
        return None

    X_train, y_train = create_sequences(train_scaled, n_steps_in, 1)
    y_train = y_train[:, 0, 0].reshape(-1, 1)

    model = Sequential([
        Bidirectional(LSTM(64, activation='relu', return_sequences=True), input_shape=(n_steps_in, train_scaled.shape[1])),
        Dropout(0.2),
        LSTM(32, activation='relu'),
        Dropout(0.2),
        Dense(1)
    ])
    optimizer = tf.keras.optimizers.Adam(learning_rate=0.005)
    model.compile(optimizer=optimizer, loss='mse')
    early_stopping = EarlyStopping(monitor='val_loss', patience=15, restore_best_weights=True)
    model.fit(X_train, y_train, epochs=50, batch_size=32, validation_split=0.2, callbacks=[early_stopping], verbose=0)

    return {
        'model': model, 'scaler_rainfall': scaler_rainfall, 'scaler_month': scaler_month,
        'scaler_oni': scaler_oni, 'last_sequence': train_scaled[-n_steps_in:],
        'last_date': monthly_data.index[-1]
    }

# --- UPDATED: Forecast future rainfall with a SCENARIO-BASED ENSO forecast ---
def forecast_lstm(model_info, forecast_steps=24):
    model, scalers = model_info['model'], {
        'rain': model_info['scaler_rainfall'], 'month': model_info['scaler_month'], 'oni': model_info['scaler_oni']
    }
    input_seq, last_date = model_info['last_sequence'].copy(), model_info['last_date']
    forecast_index = pd.date_range(start=last_date + pd.DateOffset(months=1), periods=forecast_steps, freq='M')

    # --- NEW SCENARIO-BASED ONI LOGIC ---
    # Create a plausible ONI scenario for 2025-2026 based on current long-range climate outlooks.
    # This scenario simulates a transition into a weak La Niña and then a return to neutral.
    # This provides a more realistic and scientifically-grounded input for the forecast.
    # For 2025: Start neutral and trend down to a weak La Niña (-0.7)
    oni_2025 = np.linspace(0.1, -0.7, 12)
    # For 2026: Start at weak La Niña and trend back up to neutral (0.0)
    oni_2026 = np.linspace(-0.7, 0.0, 12)
    future_oni_values = np.concatenate([oni_2025, oni_2026])

    forecast_months_scaled = scalers['month'].transform(np.array([d.month for d in forecast_index]).reshape(-1, 1))
    future_oni_scaled = scalers['oni'].transform(future_oni_values.reshape(-1, 1))

    forecasts = []
    for i in range(forecast_steps):
        yhat_scaled = model.predict(input_seq.reshape(1, input_seq.shape[0], input_seq.shape[1]), verbose=0)[0, 0]
        forecasts.append(yhat_scaled)
        new_step = np.array([[yhat_scaled, forecast_months_scaled[i, 0], future_oni_scaled[i, 0]]])
        input_seq = np.vstack((input_seq[1:], new_step))

    return {
        'forecast_index': forecast_index,
        'forecasts': scalers['rain'].inverse_transform(np.array(forecasts).reshape(-1, 1)).flatten()
    }

