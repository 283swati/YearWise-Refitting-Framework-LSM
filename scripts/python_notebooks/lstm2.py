    curr_seq = input_seq.copy()

    for i in range(forecast_steps):
        # Reshape for prediction
        x_input = curr_seq.reshape(1, curr_seq.shape[0], curr_seq.shape[1])

        # Predict next value
        yhat = model.predict(x_input, verbose=0)

