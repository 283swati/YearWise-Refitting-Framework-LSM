import numpy as np
import rasterio
from rasterio.transform import from_origin
import os
import zipfile
from tqdm import tqdm

# Configuration
input_grd_file = "/content/Rainfall_ind2024_rfp25.grd"  # Change this to your .grd file path
output_zip_file = "GRDdaily_rainfall_geotiffs2024.zip"
output_folder = "/content/GRDdaily_geotiffs2024"

# Grid parameters (from IMD documentation)
GRID_SHAPE = (129, 135)  # (latitude, longitude)
RESOLUTION = 0.25        # degrees
LON_START = 66.5         # Eastern boundary of first grid cell
LAT_START = 6.5          # Southern boundary of first grid cell

# Create output directory
os.makedirs(output_folder, exist_ok=True)

# Calculate geotransform parameters
lat_max = LAT_START + (GRID_SHAPE[0] - 1) * RESOLUTION  # 38.5N
transform = from_origin(
    LON_START - RESOLUTION/2,  # Western edge of first cell
    lat_max + RESOLUTION/2,    # Northern edge of first cell
    RESOLUTION, RESOLUTION
)

# Calculate number of days from file size
bytes_per_day = GRID_SHAPE[0] * GRID_SHAPE[1] * 4  # 4 bytes per float32
file_size = os.path.getsize(input_grd_file)
days = file_size // bytes_per_day

# Process daily data
print(f"Converting {days} days from {input_grd_file}...")
with open(input_grd_file, "rb") as f:
    for day in tqdm(range(days), desc="Processing days"):
        # Read binary data for one day
        buffer = f.read(bytes_per_day)
        if not buffer:
            break

        # Convert to numpy array and reshape
        day_data = np.frombuffer(buffer, dtype=np.float32)
        day_data = day_data.reshape(GRID_SHAPE)

        # Flip data vertically (original: south->north, needed: north->south)
        day_data = np.flipud(day_data)

        # Write GeoTIFF
        output_file = os.path.join(output_folder, f"day{day+1}.tif")
        with rasterio.open(
            output_file,
            "w",
            driver="GTiff",
            height=GRID_SHAPE[0],
            width=GRID_SHAPE[1],
            count=1,
            dtype=day_data.dtype,
            crs="EPSG:4326",
            transform=transform,
            nodata=-999.0  # From IMD's documentation
        ) as dst:
            dst.write(day_data, 1)

# Compress results (same as your original code)
print(f"Compressing GeoTIFF files into {output_zip_file}...")
with zipfile.ZipFile(output_zip_file, "w") as zipf:
    for root, _, files in os.walk(output_folder):
        for file in files:
            zipf.write(os.path.join(root, file), arcname=file)

print(f"Conversion complete! GeoTIFFs archived in {output_zip_file}")



















