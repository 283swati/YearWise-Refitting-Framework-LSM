import rasterio
from rasterio.transform import from_origin
import os
import zipfile
import re
from tqdm import tqdm
import tempfile
import shutil

# Configuration
input_zip_file = "/content/daily data 2025.zip"  # Change this to your input zip file
output_zip_file = "GRDdaily1_geotiffs2025.zip"
output_folder = "/content/GRDdaily1_geotiffs2025"

# Grid parameters (from IMD documentation)
GRID_SHAPE = (129, 135)  # (latitude, longitude)
RESOLUTION = 0.25        # degrees
LON_START = 66.5         # Eastern boundary of first grid cell
LAT_START = 6.5          # Southern boundary of first grid cell

# Create output directory
os.makedirs(output_folder, exist_ok=True)

# Calculate geotransform parameters
lat_max = LAT_START + (GRID_SHAPE[0] - 1) * RESOLUTION  # 38.5N
transform = from_origin(
    LON_START - RESOLUTION/2,  # Western edge of first cell
    lat_max + RESOLUTION/2,    # Northern edge of first cell
    RESOLUTION, RESOLUTION
)

# Create a temporary directory to extract the zip file
temp_dir = tempfile.mkdtemp()
print(f"Extracting {input_zip_file} to temporary directory...")

# Extract the zip file
with zipfile.ZipFile(input_zip_file, 'r') as zip_ref:
    zip_ref.extractall(temp_dir)

# Get all the .grd files and sort them by month and day
grd_files = []
for root, dirs, files in os.walk(temp_dir):
    for file in files:
        if file.endswith('.grd'):
            file_path = os.path.join(root, file)
            # Extract month and day from filename
            match = re.search(r'(\d{2})_(\d{2})\.grd$', file)
            if match:
                month, day = map(int, match.groups())
                grd_files.append((file_path, month, day))

# Sort files by month and day
grd_files.sort(key=lambda x: (x[1], x[2]))

print(f"Found {len(grd_files)} .grd files to process")

# Process each .grd file
day_counter = 1
for file_path, month, day in tqdm(grd_files, desc="Processing .grd files"):
    # Read the binary file
    with open(file_path, "rb") as f:
        buffer = f.read()

    # Check if we have the expected amount of data
    bytes_per_day = GRID_SHAPE[0] * GRID_SHAPE[1] * 4  # 4 bytes per float32
    if len(buffer) != bytes_per_day:
        print(f"Warning: Unexpected file size for {file_path}. Expected {bytes_per_day} bytes, got {len(buffer)} bytes.")
        continue

    # Convert to numpy array and reshape
    day_data = np.frombuffer(buffer, dtype=np.float32)
    day_data = day_data.reshape(GRID_SHAPE)

    # Flip data vertically (original: south->north, needed: north->south)
    day_data = np.flipud(day_data)

    # Write GeoTIFF
    output_file = os.path.join(output_folder, f"day{day_counter}.tif")
    with rasterio.open(
        output_file,
        "w",
        driver="GTiff",
        height=GRID_SHAPE[0],
        width=GRID_SHAPE[1],
        count=1,
        dtype=day_data.dtype,
        crs="EPSG:4326",
        transform=transform,
        nodata=-999.0  # From IMD's documentation
    ) as dst:
        dst.write(day_data, 1)

    day_counter += 1

# Clean up the temporary directory
shutil.rmtree(temp_dir)

# Compress results
print(f"Compressing GeoTIFF files into {output_zip_file}...")
with zipfile.ZipFile(output_zip_file, "w") as zipf:
    for root, _, files in os.walk(output_folder):
        for file in files:
            zipf.write(os.path.join(root, file), arcname=file)

