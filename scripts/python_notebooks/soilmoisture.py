# Create sequences for LSTM
def create_sequences(data, n_steps_in=13, n_steps_out=1):
    X, y = [], []
    for i in range(len(data) - n_steps_in - n_steps_out + 1):
        X.append(data[i:i+n_steps_in])
        y.append(data[i+n_steps_in:i+n_steps_in+n_steps_out])
    return np.array(X), np.array(y)

# Function to build and train LSTM model for a grid
def train_lstm_model(grid_id, soil_moisture_data):
    grid_cell_data = soil_moisture_data[soil_moisture_data['Grid_ID'] == grid_id]
    ts_data = grid_cell_data[['Date', 'Rootzone_Soil_Moisture']].copy()
    ts_data.set_index('Date', inplace=True)
    monthly_data = ts_data.resample('M').mean()
    monthly_data['month'] = monthly_data.index.month
    train_data = monthly_data
    scaler_sm = MinMaxScaler(feature_range=(0, 1))
    scaler_month = MinMaxScaler(feature_range=(0, 1))
    train_sm_scaled = scaler_sm.fit_transform(train_data[['Rootzone_Soil_Moisture']])
    train_month_scaled = scaler_month.fit_transform(train_data[['month']])
    train_scaled = np.hstack((train_sm_scaled, train_month_scaled))
    n_steps_in = 13
    n_steps_out = 1
    if len(train_scaled) <= n_steps_in:
        print(f"Not enough training data for Grid {grid_id}")
        return None
    X_train, y_train = create_sequences(train_scaled, n_steps_in, n_steps_out)
    y_train = y_train[:, 0, 0].reshape(-1, 1)
    input_shape = (n_steps_in, train_scaled.shape[1])
    model = Sequential()
    model.add(Bidirectional(LSTM(64, activation='relu', return_sequences=True), input_shape=input_shape))
    model.add(Dropout(0.2))
    model.add(LSTM(32, activation='relu'))
    model.add(Dropout(0.2))
    model.add(Dense(1))
    optimizer = tf.keras.optimizers.Adam(learning_rate=0.005)
    model.compile(optimizer=optimizer, loss='mse')
    early_stopping = EarlyStopping(
        monitor='val_loss',
        patience=15,
        restore_best_weights=True
    )
    model.fit(
        X_train, y_train,
        epochs=50,
        batch_size=32,
        validation_split=0.2,
        callbacks=[early_stopping],
        verbose=0
    )
    return {
        'model': model,
        'scaler_sm': scaler_sm,
        'scaler_month': scaler_month,
        'last_sequence': train_scaled[-n_steps_in:],
        'last_date': monthly_data.index[-1]
    }

# Function to forecast future soil moisture
def forecast_lstm(model_info, forecast_steps=12):
    model = model_info['model']
    scaler_sm = model_info['scaler_sm']
    scaler_month = model_info['scaler_month']
    input_seq = model_info['last_sequence']
    last_date = model_info['last_date']
    forecast_index = pd.date_range(
        start=last_date + pd.DateOffset(months=1),
        periods=forecast_steps,
        freq='M'
    )
    forecast_months = np.array([date.month for date in forecast_index]).reshape(-1, 1)
    forecast_months_scaled = scaler_month.transform(forecast_months)
    forecasts = []
    curr_seq = input_seq.copy()
    for i in range(forecast_steps):
        x_input = curr_seq.reshape(1, curr_seq.shape[0], curr_seq.shape[1])
        yhat = model.predict(x_input, verbose=0)
        forecasts.append(yhat[0, 0])
        curr_seq = np.vstack((curr_seq[1:], np.array([[yhat[0, 0], forecast_months_scaled[i, 0]]])))
    forecasts = np.array(forecasts).reshape(-1, 1)
    forecasts = scaler_sm.inverse_transform(forecasts)
    return {
        'forecast_index': forecast_index,
        'forecasts': forecasts.flatten()
    }

