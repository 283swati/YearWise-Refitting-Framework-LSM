class LSTMModel(nn.Module):
    def __init__(self, input_size, hidden_size1, hidden_size2, output_size, dropout_rate):
        super(LSTMModel, self).__init__()
        # PyTorch LSTM uses tanh/sigmoid activations internally, which is standard.
        self.lstm1 = nn.LSTM(input_size, hidden_size1, batch_first=True, bidirectional=True)
        self.dropout1 = nn.Dropout(dropout_rate)
        # Input to the second LSTM is hidden_size1 * 2 because the first is bidirectional.
        self.lstm2 = nn.LSTM(hidden_size1 * 2, hidden_size2, batch_first=True)
        self.dropout2 = nn.Dropout(dropout_rate)
        self.fc = nn.Linear(hidden_size2, output_size)

    def forward(self, x):
        out, _ = self.lstm1(x)
        out = self.dropout1(out)
        out, _ = self.lstm2(out)
        # We only need the output from the last time step for the final prediction.
        out = out[:, -1, :]
        out = self.dropout2(out)
        out = self.fc(out)
        return out

