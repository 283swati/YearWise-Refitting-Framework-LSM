    scaler_sm = MinMaxScaler(feature_range=(0, 1))
    scaler_month = MinMaxScaler(feature_range=(0, 1))
    sm_scaled = scaler_sm.fit_transform(extended_data[['Rootzone_Soil_Moisture']])
    month_scaled = scaler_month.fit_transform(extended_data[['month']])
    train_scaled = np.hstack((sm_scaled, month_scaled))

    if len(train_scaled) <= n_steps_in: return None

    X, y = create_sequences(train_scaled, n_steps_in, 1)
    y = y[:, 0, 0].reshape(-1, 1)
    split_idx = int(len(X) * 0.8)
    X_train, X_val, y_train, y_val = X[:split_idx], X[split_idx:], y[:split_idx], y[split_idx:]
    X_train_tensor, y_train_tensor = torch.from_numpy(X_train).float().to(device), torch.from_numpy(y_train).float().to(device)
    X_val_tensor, y_val_tensor = torch.from_numpy(X_val).float().to(device), torch.from_numpy(y_val).float().to(device)

    model = LSTMModel(input_size=train_scaled.shape[1], hidden_size1=64, hidden_size2=32, output_size=1, dropout_rate=0.2).to(device)
    criterion, optimizer = nn.MSELoss(), torch.optim.Adam(model.parameters(), lr=0.005)

    patience, best_val_loss, epochs_no_improve, best_model_weights = 15, float('inf'), 0, None
    for epoch in range(50):
        model.train(); optimizer.zero_grad(); outputs = model(X_train_tensor); loss = criterion(outputs, y_train_tensor); loss.backward(); optimizer.step()
        model.eval()
        with torch.no_grad(): val_loss = criterion(model(X_val_tensor), y_val_tensor).item()
        if val_loss < best_val_loss: best_val_loss, epochs_no_improve, best_model_weights = val_loss, 0, copy.deepcopy(model.state_dict())
        else: epochs_no_improve += 1
        if epochs_no_improve >= patience: break
    if best_model_weights: model.load_state_dict(best_model_weights)

    model_info = {
        'model': model,
        'scaler_sm': scaler_sm,
        'scaler_month': scaler_month,
        'last_sequence': train_scaled[-n_steps_in:],
        'last_date': extended_data.index[-1]
    }
    return forecast_pytorch(model_info, forecast_steps=forecast_steps)

