# CORRECTED EVALUATION FUNCTION
# ==============================================================================
def evaluate_pytorch_accuracy_original_method(grid_id, soil_moisture_data, n_steps_in=13):
    """
    This function replicates the ORIGINAL one-step-ahead prediction method for validation.
    It trains a model on data before 2024 and then makes predictions for each month
    of 2024 using the actual preceding data, which should result in higher accuracy scores.
    """
    grid_cell_data = soil_moisture_data[soil_moisture_data['Grid_ID'] == grid_id]
    ts_data = grid_cell_data[['Date', 'Rootzone_Soil_Moisture']].set_index('Date')
    monthly_data = ts_data.resample('M').mean()
    monthly_data['month'] = monthly_data.index.month

    train_data = monthly_data[monthly_data.index.year < 2024]
    test_data = monthly_data[monthly_data.index.year == 2024]
    if len(test_data) < 2: return None

    # --- Step 1: Train the model on pre-2024 data ---
    model_info = train_pytorch_model(grid_id, train_data)
    if not model_info: return None

    model = model_info['model']
    scaler_sm = model_info['scaler_sm']
    scaler_month = model_info['scaler_month']

    # --- Step 2: Prepare the full dataset for one-step-ahead prediction ---
    full_scaled_data = model_info['last_sequence'] # Last 13 months of training data

    test_sm_scaled = scaler_sm.transform(test_data[['Rootzone_Soil_Moisture']])
    test_month_scaled = scaler_month.transform(test_data[['month']])
    test_scaled = np.hstack((test_sm_scaled, test_month_scaled))

    # Combine last part of training data with actual test data
    input_data_np = np.vstack((full_scaled_data, test_scaled))

    # --- Step 3: Perform one-step-ahead predictions ---
    test_predictions = []
    model.eval()
    with torch.no_grad():
        for i in range(len(test_data)):
            # The input sequence is always from ground-truth data
            x_input_np = input_data_np[i : i + n_steps_in]
            x_input = torch.from_numpy(x_input_np).float().unsqueeze(0).to(device)
            yhat = model(x_input).cpu().item()
            test_predictions.append(yhat)

    test_pred_sm = scaler_sm.inverse_transform(np.array(test_predictions).reshape(-1, 1))

    # --- Step 4: Calculate metrics and plot ---
    rmse = np.sqrt(mean_squared_error(test_data['Rootzone_Soil_Moisture'].values, test_pred_sm))
    mae = mean_absolute_error(test_data['Rootzone_Soil_Moisture'].values, test_pred_sm)
    r2 = r2_score(test_data['Rootzone_Soil_Moisture'].values, test_pred_sm)
    correlation = np.corrcoef(test_data['Rootzone_Soil_Moisture'].values, test_pred_sm.flatten())[0, 1]
    mape = np.mean(np.abs((test_data['Rootzone_Soil_Moisture'].values - test_pred_sm.flatten()) / (test_data['Rootzone_Soil_Moisture'].values + 1e-6))) * 100

    plt.figure(figsize=(12, 6))
    plt.plot(test_data.index, test_data['Rootzone_Soil_Moisture'], label='Actual 2024 Soil Moisture')
    plt.plot(test_data.index, test_pred_sm, color='red', label='PyTorch LSTM Forecast (One-Step)')
    plt.title(f'PyTorch LSTM Forecast Accuracy for Grid {grid_id} (2024)', fontsize=24)
    plt.xlabel('Date', fontsize=21); plt.ylabel('Soil Moisture', fontsize=21); plt.legend(fontsize=18)
    plt.tick_params(axis='both', which='major', labelsize=15); plt.grid(True)
    plt.savefig(f'pytorch_lstm_soilmoisture_accuracy_grid_{grid_id}.png'); plt.show()

    comparison_df = pd.DataFrame({'Month': test_data.index.strftime('%Y-%m'), 'Actual': test_data['Rootzone_Soil_Moisture'].values.round(3), 'Predicted': test_pred_sm.flatten().round(3)})
    print(f"\nActual vs Predicted Soil Moisture for Grid {grid_id} (2024):\n{comparison_df}")

    return {'grid_id': grid_id, 'rmse': rmse, 'mae': mae, 'mape': mape, 'r2': r2, 'correlation': correlation}


