# Function to build and train PyTorch LSTM model for a grid
def train_pytorch_model(grid_id, soil_moisture_data, n_steps_in=13):
    grid_cell_data = soil_moisture_data[soil_moisture_data['Grid_ID'] == grid_id]
    ts_data = grid_cell_data[['Date', 'Rootzone_Soil_Moisture']].copy().set_index('Date')
    monthly_data = ts_data.resample('M').mean()
    monthly_data['month'] = monthly_data.index.month

    scaler_sm = MinMaxScaler(feature_range=(0, 1))
    scaler_month = MinMaxScaler(feature_range=(0, 1))
    train_sm_scaled = scaler_sm.fit_transform(monthly_data[['Rootzone_Soil_Moisture']])
    train_month_scaled = scaler_month.fit_transform(monthly_data[['month']])
    train_scaled = np.hstack((train_sm_scaled, train_month_scaled))

    if len(train_scaled) <= n_steps_in:
        print(f"Not enough training data for Grid {grid_id}")
        return None

    X, y = create_sequences(train_scaled, n_steps_in, 1)
    y = y[:, 0, 0].reshape(-1, 1)

    split_idx = int(len(X) * 0.8)
    X_train, X_val, y_train, y_val = X[:split_idx], X[split_idx:], y[:split_idx], y[split_idx:]

    X_train_tensor = torch.from_numpy(X_train).float().to(device)
    y_train_tensor = torch.from_numpy(y_train).float().to(device)
    X_val_tensor = torch.from_numpy(X_val).float().to(device)
    y_val_tensor = torch.from_numpy(y_val).float().to(device)

    model = LSTMModel(input_size=train_scaled.shape[1], hidden_size1=64, hidden_size2=32, output_size=1, dropout_rate=0.2).to(device)
    criterion = nn.MSELoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=0.005)

    patience, best_val_loss, epochs_no_improve, best_model_weights = 15, float('inf'), 0, None

    for epoch in range(50):
        model.train()
        optimizer.zero_grad()
        outputs = model(X_train_tensor)
        loss = criterion(outputs, y_train_tensor)
        loss.backward()
        optimizer.step()

        model.eval()
        with torch.no_grad():
            val_outputs = model(X_val_tensor)
            val_loss = criterion(val_outputs, y_val_tensor).item()

        if val_loss < best_val_loss:
            best_val_loss, epochs_no_improve, best_model_weights = val_loss, 0, copy.deepcopy(model.state_dict())
        else:
            epochs_no_improve += 1
        if epochs_no_improve >= patience:
            break

    if best_model_weights:
        model.load_state_dict(best_model_weights)

    return {
        'model': model,
        'scaler_sm': scaler_sm,
        'scaler_month': scaler_month,
        'last_sequence': train_scaled[-n_steps_in:],
        'last_date': monthly_data.index[-1],
        'monthly_data': monthly_data
    }

# Function to forecast future soil moisture with PyTorch model
def forecast_pytorch(model_info, forecast_steps=12):
    model = model_info['model']
    scaler_sm = model_info['scaler_sm']
    scaler_month = model_info['scaler_month']
    input_seq_np = model_info['last_sequence']
    last_date = model_info['last_date']

    forecast_index = pd.date_range(start=last_date + pd.DateOffset(months=1), periods=forecast_steps, freq='M')
    forecast_months = np.array([date.month for date in forecast_index]).reshape(-1, 1)
    forecast_months_scaled = scaler_month.transform(forecast_months)

    forecasts = []
    curr_seq_np = input_seq_np.copy()

    model.eval()
    with torch.no_grad():
        for i in range(forecast_steps):
            x_input = torch.from_numpy(curr_seq_np).float().unsqueeze(0).to(device)
            yhat_tensor = model(x_input)
            yhat = yhat_tensor.cpu().item()
            forecasts.append(yhat)
            new_row = np.array([[yhat, forecast_months_scaled[i, 0]]])
            curr_seq_np = np.vstack((curr_seq_np[1:], new_row))

    forecasts = np.array(forecasts).reshape(-1, 1)
    forecasts = scaler_sm.inverse_transform(forecasts)

    return {
        'forecast_index': forecast_index,
        'forecasts': forecasts.flatten()
    }

